import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
const dir=new URL("../data/templates/",import.meta.url);
const old=JSON.parse(await readFile(new URL("H0D_Actor-template-creature-v1.20.json",dir),"utf8"));
const next=JSON.parse(await readFile(new URL("H0D_Actor-template-creature-v1.21.json",dir),"utf8"));
assert.equal(next._id,old._id);
assert.equal(next.system.templateSystemUniqueVersion,3034657903);
const panels=next.system.body.contents[0].contents[0].contents[0].contents;
const prevPanels=old.system.body.contents[0].contents[0].contents[0].contents;
assert.equal(panels.length,prevPanels.length);
const panel=panels[2],prior=prevPanels[2];
assert.equal(panel.visibilityFormula,"equalText(H0D_Creature_Faction,'CaravanesLibres')");
assert.equal(panel.contents.length,prior.contents.length+1);
const label=panel.contents[1];
assert.equal(label.key,"H0D_Creature_Niveau_Ordinaire_Aff");
assert.ok(label.value.includes("${H0D_Creature_Niveau_PNJ}$"));
assert.ok(label.value.includes("${H0D_Creature_Menace}$"));
const identical=structuredClone(next);
identical.name=old.name;
identical.system.templateSystemUniqueVersion=old.system.templateSystemUniqueVersion;
identical.system.body.contents[0].contents[0].contents[0].contents[2].contents.splice(1,1);
assert.deepEqual(identical,old,"No changes to existing CSB components or combat calculations");
console.log("OK: NPC level vs CR label; all prior template formulas unchanged.");
