import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
const base=new URL("../data/templates/",import.meta.url);
const old=JSON.parse(await readFile(new URL("H0D_Actor-template-creature-v1.19.json",base),"utf8"));
const updated=JSON.parse(await readFile(new URL("H0D_Actor-template-creature-v1.20.json",base),"utf8"));
assert.equal(updated._id,old._id);
assert.equal(updated.system.templateSystemUniqueVersion,3034657902);
const panels=updated.system.body.contents[0].contents[0].contents[0].contents;
const oldPanels=old.system.body.contents[0].contents[0].contents[0].contents;
assert.equal(panels.length,oldPanels.length+1);
const scorePanel=panels[2];
assert.equal(scorePanel.visibilityFormula,"equalText(H0D_Creature_Faction,'CaravanesLibres')");
assert.equal(scorePanel.contents[1].type,"table");
assert.equal(scorePanel.contents[1].rows,"1");
const stats=["FOR","DEX","CON","INT","SAG","CHA"];
assert.deepEqual(scorePanel.contents[1].contents[0].map(x=>x.key),stats.map(x=>"H0D_Creature_"+x+"_SCORE"));
for(const field of scorePanel.contents[1].contents[0])assert.equal(field.type,"numberField");
const clone=structuredClone(updated);
clone.name=old.name;
clone.system.templateSystemUniqueVersion=old.system.templateSystemUniqueVersion;
clone.system.body.contents[0].contents[0].contents[0].contents.splice(2,1);
assert.deepEqual(clone,old,"No combat formulas or other creature sections may change");
console.log("OK: Caravanes score panel isolated; prior creature formulas unchanged");
